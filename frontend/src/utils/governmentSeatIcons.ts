const SVG_NS = 'http://www.w3.org/2000/svg';

/** O ícone de um cargo como elemento SVG, do tamanho e da cor pedidos (para o cartão de compartilhamento). */
export function seatIconElement(seatKey: GovernmentSeat['seatKey'], size: number, color: string): SVGElement {
  const icon = SEAT_ICONS[seatKey];
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', icon.viewBox);
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('aria-hidden', 'true');
  svg.style.display = 'block';
  svg.style.flex = 'none';
  svg.style.color = color;
  for (const { d, evenodd } of icon.paths) {
    const path = document.createElementNS(SVG_NS, 'path');
    path.setAttribute('d', d);
    path.setAttribute('fill', 'currentColor');
    if (evenodd) {
      path.setAttribute('fill-rule', 'evenodd');
      path.setAttribute('clip-rule', 'evenodd');
    }
    svg.append(path);
  }
  return svg;
}
